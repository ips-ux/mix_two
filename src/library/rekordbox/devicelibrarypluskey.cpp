namespace {

// Mix Two: the passphrase XOR a 16 byte mask, repeated. The mask only keeps
// the passphrase out of a plain text search of the source and the program. It
// is no protection: the passphrase is public.
// clang-format off
constexpr unsigned char kMask[16] = {
        0x31, 0x24, 0x09, 0x9c, 0x17, 0x3e, 0x39, 0x91,
        0xde, 0x48, 0xa6, 0x93, 0xfc, 0xff, 0x6f, 0x57,
};

constexpr unsigned char kMasked[64] = {
        0x43, 0x1c, 0x6e, 0xf8, 0x73, 0x50, 0x4b, 0xa5,
        0xb5, 0x70, 0x92, 0xa4, 0xc4, 0xcc, 0x5f, 0x36,
        0x43, 0x12, 0x6a, 0xed, 0x6d, 0x5c, 0x52, 0xfa,
        0xee, 0x2d, 0xca, 0xa5, 0x8d, 0x86, 0x1b, 0x3a,
        0x53, 0x17, 0x7d, 0xee, 0x75, 0x5c, 0x41, 0xa9,
        0xee, 0x7d, 0xcc, 0xfe, 0xcb, 0xcb, 0x19, 0x32,
        0x4b, 0x12, 0x3d, 0xf5, 0x22, 0x51, 0x01, 0xf7,
        0xb0, 0x3a, 0xd7, 0xe1, 0x85, 0x8e, 0x03, 0x24,
};
// clang-format on

} // namespace

QByteArray deviceLibraryPlusPassphrase() {
    QByteArray passphrase(static_cast<qsizetype>(sizeof(kMasked)), Qt::Uninitialized);
    for (std::size_t i = 0; i < sizeof(kMasked); ++i) {
        passphrase[static_cast<qsizetype>(i)] =
                static_cast<char>(kMasked[i] ^ kMask[i % sizeof(kMask)]);
    }
    return passphrase;
}

