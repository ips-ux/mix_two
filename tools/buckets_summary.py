"""Generate docs/ddj800-program/BUCKETS.md from the bucket files.

Reads every table row in docs/ddj800-program/buckets/*.md, counts the
Status column, and writes the fill summary. Run from the repository root:

    python tools/buckets_summary.py

Fill rules (DECISIONS.md section 3): rows marked Skip are left out. In the
hardware buckets only Deck-verified and CDJ-verified count as filled; in the
other buckets Checked counts too.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BUCKET_DIR = ROOT / "docs" / "ddj800-program" / "buckets"
OUT = ROOT / "docs" / "ddj800-program" / "BUCKETS.md"

STATUSES = ["Build", "Partial", "Built", "Checked", "Deck-verified", "CDJ-verified", "Skip"]
# Buckets whose rows need the owner's hands on the deck (or rekordbox / a CDJ
# for export) before they count as filled.
HARDWARE_BUCKETS = {"01", "02", "03", "04", "06", "09", "10b", "10c", "11"}


def parse_bucket(path):
    text = path.read_text(encoding="utf-8")
    title = re.search(r"^# (.+)$", text, re.M)
    crit = re.search(r"\*\*Criticality:\*\*\s*([^·\n]+)", text)
    counts = dict.fromkeys(STATUSES, 0)
    header = None
    for line in text.splitlines():
        if not line.startswith("|"):
            header = None
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if header is None:
            header = cells
            continue
        if set(line.replace("|", "").strip()) <= set("-: "):
            continue
        if "Status" not in header or len(cells) != len(header):
            continue
        row = dict(zip(header, cells))
        # Cross-reference rows ("See CTL-012.") point at a row in another
        # bucket; count the feature once, where it lives.
        if row.get("Src", "-") in ("", "-") and row.get("Notes", "").lower().startswith("see "):
            continue
        status = row["Status"]
        if status in counts:
            counts[status] += 1
    return (title.group(1).strip() if title else path.stem,
            crit.group(1).strip() if crit else "?",
            counts)


def main():
    files = sorted(BUCKET_DIR.glob("*.md"))
    if not files:
        sys.exit("no bucket files in " + str(BUCKET_DIR))
    lines = [
        "<!-- Generated by tools/buckets_summary.py. Do not edit by hand. -->",
        "",
        "# Mix Two buckets: fill summary",
        "",
        "Generated from the bucket files in [buckets/](buckets/). Rules and the",
        "status ladder: [DECISIONS.md](DECISIONS.md) section 3. Skip rows are left",
        "out of the fill. Hardware buckets (marked *) count only Deck-verified and",
        "CDJ-verified rows; the others count Checked rows too.",
        "",
        "| Bucket | Criticality | Rows | Fill | " + " | ".join(STATUSES) + " |",
        "|---|---|---|---|" + "---|" * len(STATUSES),
    ]
    total = dict.fromkeys(STATUSES, 0)
    for path in files:
        key = path.stem.split("-", 1)[0]
        title, crit, counts = parse_bucket(path)
        for s in STATUSES:
            total[s] += counts[s]
        rows = sum(counts.values())
        live = rows - counts["Skip"]
        filled = counts["Deck-verified"] + counts["CDJ-verified"]
        if key not in HARDWARE_BUCKETS:
            filled += counts["Checked"]
        fill = f"{100 * filled / live:.0f}%" if live else "n/a"
        mark = "*" if key in HARDWARE_BUCKETS else ""
        lines.append(f"| [{title}{mark}](buckets/{path.name}) | {crit} | {rows} | {fill} | "
                     + " | ".join(str(counts[s]) for s in STATUSES) + " |")
    lines.append("| **All** | | " + str(sum(total.values())) + " | | "
                 + " | ".join(str(total[s]) for s in STATUSES) + " |")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
